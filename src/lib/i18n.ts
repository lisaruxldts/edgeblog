export function getDict(lang: string): Dict {
	const l = lang.toLowerCase();
	if (dicts[l]) return dicts[l];
	if (l === "zh-hk" || l === "zh-hant") return dicts["zh-tw"];
	return dicts[l.split("-")[0]] ?? en;
}

export const fill = (template: string, vars: Record<string, string | number>): string =>
	template.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
